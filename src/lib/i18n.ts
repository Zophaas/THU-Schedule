// UI language. The current language is module state so plain formatting helpers
// (weeks, days, periods) can use it; App sets it before rendering and includes it
// in memo dependencies so derived text is recomputed when it changes.

export type Lang = 'en' | 'zh';

let current: Lang = 'zh';

export function setLang(lang: Lang) {
  current = lang;
}

export function getLang(): Lang {
  return current;
}

export function defaultLang(): Lang {
  return typeof navigator !== 'undefined' && navigator.language.toLowerCase().startsWith('zh') ? 'zh' : 'en';
}

