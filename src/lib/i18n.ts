const MESSAGES: Record<Lang, Messages> = { en, zh };

export type MessageKey = keyof typeof en;

export function t(key: MessageKey, vars: Record<string, string | number> = {}): string {
  // Placeholders are written {name}; unknown names are left as they are.
  return MESSAGES[current][key].replace(/\{(\w+)\}/g, (match, name: string) =>
    name in vars ? String(vars[name]) : match,
  );
}

/** Pick the singular key when n is 1. */
export function tn(n: number, one: MessageKey, many: MessageKey, vars: Record<string, string | number> = {}): string {
  return t(n === 1 ? one : many, { n, ...vars });
}

/** Course name for the current language; falls back to Chinese when no English name exists. */
export function courseName(course: { course_name: string; course_name_en?: string | null }): string {
  return current === 'en' && course.course_name_en ? course.course_name_en : course.course_name;
}
